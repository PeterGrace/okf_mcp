#[cfg(all(test, target_os = "linux"))]
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Fault {
    FileSync,
    Rename,
    DirectorySync,
}
#[cfg(all(test, target_os = "linux"))]
thread_local! { static FAULT: std::cell::Cell<Option<Fault>> = const { std::cell::Cell::new(None) }; }
#[cfg(all(test, target_os = "linux"))]
thread_local! { static SAVE_FAULT: std::cell::Cell<Option<(usize, Fault)>> = const { std::cell::Cell::new(None) }; }
#[cfg(all(test, target_os = "linux"))]
pub(super) fn fail_save_after(saves: usize, fault: Fault) {
    SAVE_FAULT.with(|slot| slot.set(Some((saves, fault))));
}
#[cfg(all(test, target_os = "linux"))]
fn begin_save() {
    SAVE_FAULT.with(|slot| {
        if let Some((remaining, fault)) = slot.get() {
            if remaining == 0 {
                slot.set(None);
                FAULT.with(|active| active.set(Some(fault)));
            } else {
                slot.set(Some((remaining - 1, fault)));
            }
        }
    });
}
#[cfg(all(test, target_os = "linux"))]
fn inject(stage: Fault) -> Result<(), RunnerError> {
    FAULT.with(|fault| {
        if fault.get() == Some(stage) {
            fault.set(None);
            Err(RunnerError::Io)
        } else {
            Ok(())
        }
    })
}

