//! Private, locked persistence for exact mutation replay.
//!
//! A save error is fatal to the caller's current operation: in particular, a
//! directory-sync error can mean the complete new journal is already visible.
//! Reopen and recover; never infer that a failed save permits a fresh request.
//! This module stores no bearer credential and deliberately implements no Debug.
//!
//! ```compile_fail
//! use okf_mcp::investigator::{journal::Journal, types::Binding};
//! fn leak(state: &Journal) { println!("{state:?}"); }
//! ```

use serde::{Deserialize, Serialize};
use std::{collections::HashSet, path::Path};

use super::{
    contract,
    error::RunnerError,
    types::{AllowedTool, Binding, ModelUsage, Packet, Proposal, ToolRequest},
};
use crate::maintenance::types::{Lease, Receipt};

#[derive(Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Journal {
    pub schema_version: u32,
    pub binding: Binding,
    pub run_id: Option<String>,
    pub leases: Vec<Lease>,
    pub work: Vec<WorkState>,
    pub pending: Option<PendingMutation>,
    pub receipts: Vec<Receipt>,
    pub invocations: u32,
    pub reserved_microusd: u64,
    pub usage: ModelUsage,
    pub accounting_known: bool,
    /// First operational stop cause; independent of per-work accounting markers.
    #[serde(default)]
    pub stop_reason: Option<String>,
    pub terminal: bool,
}

#[derive(Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PendingMutation {
    pub request_id: String,
    pub request: ToolRequest,
}

#[derive(Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Phase {
    Claimed,
    PacketReady,
    InvocationStarted,
    ProposalReady,
    SubmissionPending,
    Reported,
    Abandoned,
}

#[derive(Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct WorkState {
    pub work_id: String,
    pub phase: Phase,
    pub packet: Option<Packet>,
    pub proposal: Option<Proposal>,
    pub usage: Option<ModelUsage>,
    pub failure: Option<String>,
}

impl Phase {
    fn permits(self, next: Self) -> bool {
        self == next
            || matches!(
                (self, next),
                (
                    Self::Claimed,
                    Self::PacketReady | Self::SubmissionPending | Self::Abandoned
                ) | (
                    Self::PacketReady,
                    Self::InvocationStarted | Self::SubmissionPending | Self::Abandoned
                ) | (
                    Self::InvocationStarted,
                    Self::ProposalReady | Self::SubmissionPending | Self::Abandoned
                ) | (
                    Self::ProposalReady,
                    Self::SubmissionPending | Self::Abandoned
                ) | (Self::SubmissionPending, Self::Reported | Self::Abandoned)
            )
    }
}

fn usage_totals(usage: &ModelUsage) -> [u64; 5] {
    [
        usage.input,
        usage.output,
        usage.cache_creation,
        usage.cache_read,
        usage.cost_microusd,
    ]
}

fn valid_failure(value: &str) -> bool {
    matches!(
        value,
        "config"
            | "permission"
            | "contract"
            | "transport"
            | "lease_lost"
            | "budget"
            | "invalid_evidence"
            | "invalid_proposal"
            | "unknown_accounting"
            | "child"
            | "journal"
            | "cancelled"
            | "io"
    )
}

fn unresolved(work: &WorkState) -> bool {
    work.usage.is_none()
        && (work.phase == Phase::InvocationStarted
            || work.failure.as_deref() == Some("unknown_accounting"))
}

fn valid_key(key: &str) -> bool {
    !key.is_empty() && key.len() <= 128 && key.bytes().all(|b| b.is_ascii_graphic())
}

impl PendingMutation {
    /// Normalize once, before persistence and before the first remote call.
    /// Keys are generated by the controller with maintenance::types::new_id.
    pub fn new(request: ToolRequest, catalog: &str) -> Result<Self, RunnerError> {
        let tool = request.tool;
        if !matches!(
            tool,
            AllowedTool::Claim | AllowedTool::Renew | AllowedTool::Submit | AllowedTool::Close
        ) {
            return Err(RunnerError::Journal);
        }
        let args = serde_json::Value::Object(
            contract::arguments(request, catalog).map_err(|_| RunnerError::Journal)?,
        );
        let request_id = args
            .get("idempotency_key")
            .and_then(|v| v.as_str())
            .filter(|key| valid_key(key))
            .ok_or(RunnerError::Journal)?
            .to_owned();
        Ok(Self {
            request_id,
            request: ToolRequest { tool, args },
        })
    }

    fn validate(&self, catalog: &str) -> Result<(), RunnerError> {
        let normalized = Self::new(self.request.clone(), catalog)?;
        if normalized.request_id != self.request_id || normalized.request.args != self.request.args
        {
            return Err(RunnerError::Journal);
        }
        Ok(())
    }
}

fn validate_binding(binding: &Binding) -> Result<(), RunnerError> {
    let url = reqwest::Url::parse(&binding.endpoint).map_err(|_| RunnerError::Journal)?;
    if url.scheme() != "https"
        || url.host_str().is_none()
        || !url.username().is_empty()
        || url.password().is_some()
        || url.fragment().is_some()
        || url.as_str() != binding.endpoint
        || url.origin().ascii_serialization() != binding.origin
        || binding.catalog.trim().is_empty()
        || binding.credential_sha256.len() != 64
        || !binding
            .credential_sha256
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
    {
        return Err(RunnerError::Journal);
    }
    Ok(())
}

impl Journal {
    pub fn new(binding: Binding) -> Self {
        Self {
            schema_version: 1,
            binding,
            run_id: None,
            leases: Vec::new(),
            work: Vec::new(),
            pending: None,
            receipts: Vec::new(),
            invocations: 0,
            reserved_microusd: 0,
            usage: ModelUsage {
                input: 0,
                output: 0,
                cache_creation: 0,
                cache_read: 0,
                cost_microusd: 0,
            },
            accounting_known: true,
            stop_reason: None,
            terminal: false,
        }
    }

    fn validate(&self, binding: &Binding) -> Result<(), RunnerError> {
        let bad = RunnerError::Journal;
        validate_binding(binding)?;
        if self.schema_version != 1
            || &self.binding != binding
            || self.run_id.as_ref().is_some_and(|id| id.is_empty())
            || self
                .stop_reason
                .as_deref()
                .is_some_and(|reason| !valid_failure(reason))
        {
            return Err(bad);
        }
        let run = self.run_id.as_deref();
        if run.is_none()
            && (!self.leases.is_empty() || !self.work.is_empty() || !self.receipts.is_empty())
        {
            return Err(bad);
        }
        if self.accounting_known && self.work.iter().any(unresolved) {
            return Err(bad);
        }
        let mut work_ids = HashSet::new();
        for work in &self.work {
            if work.work_id.is_empty() || !work_ids.insert(&work.work_id) {
                return Err(bad);
            }
            if let Some(failure) = &work.failure {
                if !valid_failure(failure) {
                    return Err(bad);
                }
            }
            if work
                .packet
                .as_ref()
                .is_some_and(|p| p.work_id != work.work_id)
                || work.proposal.is_some() && work.packet.is_none()
                || work.usage.is_some() && work.packet.is_none()
            {
                return Err(bad);
            }
            match work.phase {
                Phase::Claimed
                    if work.packet.is_some() || work.proposal.is_some() || work.usage.is_some() =>
                {
                    return Err(bad)
                }
                Phase::PacketReady | Phase::InvocationStarted
                    if work.packet.is_none() || work.proposal.is_some() || work.usage.is_some() =>
                {
                    return Err(bad)
                }
                Phase::ProposalReady
                    if work.packet.is_none() || work.proposal.is_none() || work.usage.is_none() =>
                {
                    return Err(bad)
                }
                _ => {}
            }
            if self.terminal && !matches!(work.phase, Phase::Reported | Phase::Abandoned) {
                return Err(bad);
            }
        }
        let mut leased = HashSet::new();
        for lease in &self.leases {
            if Some(lease.run_id.as_str()) != run
                || !work_ids.contains(&lease.work_id)
                || !leased.insert(&lease.work_id)
                || lease.token.is_empty()
                || lease.pin.revision <= 0
            {
                return Err(bad);
            }
        }
        let mut receipted = HashSet::new();
        for receipt in &self.receipts {
            if Some(receipt.run_id.as_str()) != run
                || !work_ids.contains(&receipt.work_id)
                || !receipted.insert(&receipt.work_id)
                || !self
                    .work
                    .iter()
                    .any(|w| w.work_id == receipt.work_id && w.phase == Phase::Reported)
            {
                return Err(bad);
            }
        }
        for work in &self.work {
            if work.phase == Phase::Reported && !receipted.contains(&work.work_id)
                || !matches!(work.phase, Phase::Reported | Phase::Abandoned)
                    && !leased.contains(&work.work_id)
            {
                return Err(bad);
            }
        }
        if let Some(pending) = &self.pending {
            pending.validate(&binding.catalog)?;
            if self.terminal {
                return Err(bad);
            }
            let args = &pending.request.args;
            match pending.request.tool {
                AllowedTool::Claim if run.is_none() => {}
                AllowedTool::Close if run.is_some() && args["run_id"].as_str() == run => {}
                AllowedTool::Renew | AllowedTool::Submit if run.is_some() => {
                    let lease = self
                        .leases
                        .iter()
                        .find(|l| args["work_id"] == l.work_id && args["token"] == l.token)
                        .ok_or(bad)?;
                    let work = self
                        .work
                        .iter()
                        .find(|w| w.work_id == lease.work_id)
                        .ok_or(bad)?;
                    if matches!(work.phase, Phase::Reported | Phase::Abandoned)
                        || pending.request.tool == AllowedTool::Submit
                            && work.phase != Phase::SubmissionPending
                    {
                        return Err(bad);
                    }
                }
                _ => return Err(bad),
            }
        }
        for work in &self.work {
            if work.phase == Phase::SubmissionPending
                && !self.pending.as_ref().is_some_and(|p| {
                    p.request.tool == AllowedTool::Submit
                        && p.request.args["work_id"] == work.work_id
                })
            {
                return Err(bad);
            }
        }
        Ok(())
    }

    fn follows(&self, previous: &Self) -> Result<(), RunnerError> {
        let bad = RunnerError::Journal;
        // Only an explicit fresh state may replace a terminal run. Ordinary
        // saves cannot discard work, receipts, or an ambiguous request.
        if previous.terminal {
            let fresh = Self::new(self.binding.clone());
            if serde_json::to_value(self).map_err(|_| bad)?
                == serde_json::to_value(fresh).map_err(|_| bad)?
            {
                return Ok(());
            }
            if !self.terminal {
                return Err(bad);
            }
        }
        if previous.stop_reason.is_some() && self.stop_reason != previous.stop_reason {
            return Err(bad);
        }
        if previous.run_id.is_some() && self.run_id != previous.run_id
            || previous
                .work
                .iter()
                .any(|old| !self.work.iter().any(|w| w.work_id == old.work_id))
            || previous
                .receipts
                .iter()
                .any(|old| !self.receipts.contains(old))
        {
            return Err(bad);
        }
        if self.invocations < previous.invocations
            || self.reserved_microusd < previous.reserved_microusd
            || usage_totals(&self.usage)
                .iter()
                .zip(usage_totals(&previous.usage))
                .any(|(new, old)| *new < old)
        {
            return Err(bad);
        }
        let mut added_usage = [0u64; 5];
        let mut recorded_usage = false;
        let mut started = 0u32;
        for old in &previous.work {
            let new = self
                .work
                .iter()
                .find(|w| w.work_id == old.work_id)
                .ok_or(bad)?;
            if !old.phase.permits(new.phase) {
                return Err(bad);
            }
            if new.phase == Phase::InvocationStarted && old.phase != Phase::InvocationStarted {
                started += 1;
            }
            if let Some(usage) = &old.usage {
                if new.usage.as_ref() != Some(usage) {
                    return Err(bad);
                }
            } else if let Some(usage) = &new.usage {
                // Usage resolves an actual started invocation, including a later
                // reconciliation of one explicitly marked unknown; never retry.
                if !unresolved(old) {
                    return Err(bad);
                }
                recorded_usage = true;
                for (sum, value) in added_usage.iter_mut().zip(usage_totals(usage)) {
                    *sum = sum.checked_add(value).ok_or(bad)?;
                }
            }
            if unresolved(old) && new.usage.is_none() && !unresolved(new) {
                return Err(bad);
            }
        }
        if started > 0
            && (started != 1
                || !previous.accounting_known
                || self.accounting_known
                || self.invocations != previous.invocations.checked_add(1).ok_or(bad)?
                || self.reserved_microusd <= previous.reserved_microusd)
        {
            return Err(bad);
        }
        if recorded_usage {
            for ((new, old), added) in usage_totals(&self.usage)
                .into_iter()
                .zip(usage_totals(&previous.usage))
                .zip(added_usage)
            {
                if new != old.checked_add(added).ok_or(bad)? {
                    return Err(bad);
                }
            }
        }
        if !previous.accounting_known
            && self.accounting_known
            && (!recorded_usage
                || self.work.iter().any(unresolved)
                || self.invocations != previous.invocations
                || self.reserved_microusd != previous.reserved_microusd)
        {
            return Err(bad);
        }
        if let Some(old) = &previous.pending {
            if let Some(new) = &self.pending {
                if old.request_id != new.request_id
                    || old.request.tool != new.request.tool
                    || old.request.args != new.request.args
                {
                    return Err(bad);
                }
            } else {
                match old.request.tool {
                    AllowedTool::Claim if self.run_id.is_some() => {}
                    AllowedTool::Renew
                        if self
                            .leases
                            .iter()
                            .any(|l| old.request.args["work_id"] == l.work_id) => {}
                    AllowedTool::Submit
                        if self
                            .receipts
                            .iter()
                            .any(|r| old.request.args["work_id"] == r.work_id) => {}
                    AllowedTool::Close if self.terminal => {}
                    _ => return Err(bad),
                }
            }
        }
        Ok(())
    }
}

